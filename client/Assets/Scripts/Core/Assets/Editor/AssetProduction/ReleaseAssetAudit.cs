        /// <summary>Loads all fragment rows tagged by fragment name.</summary>
        private static List<Row> LoadRows(string repoRoot, Report report)
        {
            var rows = new List<Row>();
            string dir = Path.Combine(repoRoot,
                FragmentsDir.Replace('/', Path.DirectorySeparatorChar));
            if (!Directory.Exists(dir))
            {
                Add(report, "register", FragmentsDir, "fragment directory missing");
                return rows;
            }
            var files = Directory.GetFiles(dir, "*.json");
            Array.Sort(files, StringComparer.Ordinal);
            var seen = new HashSet<string>(StringComparer.Ordinal);
            foreach (var f in files)
            {
                string frag = Path.GetFileNameWithoutExtension(f);
                RegisterJson.Node root;
                try
                {
                    root = RegisterJson.Parse(File.ReadAllText(f));
                }
                catch (RegisterJson.ParseException ex)
                {
                    Add(report, "register", FragmentsDir + "/" + frag + ".json",
                        "invalid JSON: " + ex.Message);
                    continue;
                }
                var assets = root.Get("assets");
                if (assets == null || assets.Type != RegisterJson.Node.Kind.Arr)
                {
                    Add(report, "register", FragmentsDir + "/" + frag + ".json",
                        "assets array missing");
                    continue;
                }
                for (int i = 0; i < assets.Arr!.Count; i++)
                {
                    var n = assets.Arr[i];
                    var row = new Row
                    {
                        Node = n,
                        Fragment = frag,
                        FilePath = StrField(n, "file_path") ?? string.Empty,
                        AssetKey = StrField(n, "asset_key") ?? string.Empty,
                    };
                    if (row.FilePath.Length == 0)
                    {
                        Add(report, "register", frag + "[" + i.ToString(
                            CultureInfo.InvariantCulture) + "]",
                            "file_path missing");
                        continue;
                    }
                    if (!seen.Add(row.FilePath))
                    {
                        Add(report, "register", row.FilePath,
                            "file_path duplicated across fragments");
                    }
                    rows.Add(row);
                }
            }
            rows.Sort((a, b) => string.CompareOrdinal(a.FilePath, b.FilePath));
            report.RowsChecked = rows.Count;
            return rows;
        }

        /// <summary>Parses the committed merged register into rows.</summary>
        private static List<Row> LoadCommittedRegister(string repoRoot,
            Report report)
        {
            var rows = new List<Row>();
            string p = Path.Combine(repoRoot,
                RegisterRelativePath.Replace('/', Path.DirectorySeparatorChar));
            if (!File.Exists(p))
            {
                return rows;
            }
            RegisterJson.Node root;
            try
            {
                root = RegisterJson.Parse(File.ReadAllText(p));
            }
            catch (RegisterJson.ParseException ex)
            {
                Add(report, "register", RegisterRelativePath,
                    "invalid JSON: " + ex.Message);
                return rows;
            }
            var assets = root.Get("assets");
            if (assets == null || assets.Type != RegisterJson.Node.Kind.Arr)
            {
                return rows;
            }
            for (int i = 0; i < assets.Arr!.Count; i++)
            {
                var n = assets.Arr[i];
                rows.Add(new Row
                {
                    Node = n,
                    Fragment = "register",
                    FilePath = StrField(n, "file_path") ?? string.Empty,
                    AssetKey = StrField(n, "asset_key") ?? string.Empty,
                });
            }
            return rows;
        }

        /// <summary>
        /// Deterministic merged register text: union of fragment rows,
        /// file_path-unique, sorted by file_path ascending; rows that pass
        /// the rights checks are emitted APPROVED, the rest keep their
        /// fragment verdict.
        /// </summary>
        public static string MergeRegisterText(string repoRoot)
        {
            var rows = LoadRows(repoRoot, new Report());
            return MergeRegisterTextFromRows(repoRoot, rows,
                LoadCulturalApprovals(repoRoot));
        }

        private static string MergeRegisterTextFromRows(
            string repoRoot, List<Row> rows, HashSet<string> cultural)
        {
            var outRows = new List<RegisterJson.Node>();
            for (int i = 0; i < rows.Count; i++)
            {
                var row = rows[i];
                var clone = CloneNode(row.Node);
                var rs = clone.Get("review_state");
                if (rs != null
                    && RowRightsIssues(repoRoot, row, cultural).Count == 0)
                {
                    rs.Str = "APPROVED";
                }
                outRows.Add(clone);
            }
            var root = new Dictionary<string, RegisterJson.Node>(
                StringComparer.Ordinal);
            root["schema_version"] = RegisterJson.Node.NumNode(1);
            root["assets"] = RegisterJson.Node.ArrNode(outRows);
            var sb = new StringBuilder();
            WriteNode(RegisterJson.Node.ObjNode(root), sb, 0);
            sb.Append('\n');
            return sb.ToString();
        }

        private static RegisterJson.Node CloneNode(RegisterJson.Node n)
        {
            switch (n.Type)
            {
                case RegisterJson.Node.Kind.Obj:
                    var o = new Dictionary<string, RegisterJson.Node>(
                        StringComparer.Ordinal);
                    foreach (var kv in n.Obj!)
                    {
                        o[kv.Key] = CloneNode(kv.Value);
                    }
                    return RegisterJson.Node.ObjNode(o);
                case RegisterJson.Node.Kind.Arr:
                    var a = new List<RegisterJson.Node>(n.Arr!.Count);
                    for (int i = 0; i < n.Arr!.Count; i++)
                    {
                        a.Add(CloneNode(n.Arr[i]));
                    }
                    return RegisterJson.Node.ArrNode(a);
                case RegisterJson.Node.Kind.Str:
                    return RegisterJson.Node.StrNode(n.Str);
                case RegisterJson.Node.Kind.Num:
                    return RegisterJson.Node.NumNode(n.Num);
                case RegisterJson.Node.Kind.Bool:
                    return RegisterJson.Node.BoolNode(n.Bool);
                default:
                    return RegisterJson.Node.NullNode();
            }
        }

        /// <summary>
        /// Serializes a node in the canonical fragment layout: one-space
        /// indent per level, <c>"k": v</c> pairs, empty containers inline —
        /// byte-equal to <c>json.dumps(indent=1, ensure_ascii=False)</c>
        /// plus a trailing newline.
        /// </summary>
        public static void WriteNode(RegisterJson.Node n, StringBuilder sb,
            int depth)
        {
            string ind = new string(' ', depth + 1);
            switch (n.Type)
            {
                case RegisterJson.Node.Kind.Obj:
                    if (n.Obj!.Count == 0)
                    {
                        sb.Append("{}");
                        break;
                    }
                    sb.Append("{\n");
                    bool first = true;
                    foreach (var kv in n.Obj)
                    {
                        if (!first)
                        {
                            sb.Append(",\n");
                        }
                        first = false;
                        sb.Append(ind);
                        WriteString(sb, kv.Key);
                        sb.Append(": ");
                        WriteNode(kv.Value, sb, depth + 1);
                    }
                    sb.Append('\n').Append(new string(' ', depth)).Append('}');
                    break;
                case RegisterJson.Node.Kind.Arr:
                    if (n.Arr!.Count == 0)
                    {
                        sb.Append("[]");
                        break;
                    }
                    sb.Append("[\n");
                    for (int i = 0; i < n.Arr.Count; i++)
                    {
                        if (i != 0)
                        {
                            sb.Append(",\n");
                        }
                        sb.Append(ind);
                        WriteNode(n.Arr[i], sb, depth + 1);
                    }
                    sb.Append('\n').Append(new string(' ', depth)).Append(']');
                    break;
                case RegisterJson.Node.Kind.Str:
                    WriteString(sb, n.Str);
                    break;
                case RegisterJson.Node.Kind.Num:
                    double v = n.Num;
                    if (v == Math.Floor(v) && Math.Abs(v) < 1e15)
                    {
                        sb.Append(((long)v).ToString(CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        sb.Append(v.ToString("R", CultureInfo.InvariantCulture));
                    }
                    break;
                case RegisterJson.Node.Kind.Bool:
                    sb.Append(n.Bool ? "true" : "false");
                    break;
                default:
                    sb.Append("null");
                    break;
            }
        }

        private static void WriteString(StringBuilder sb, string s)
        {
            sb.Append('"');
            for (int i = 0; i < s.Length; i++)
            {
                char c = s[i];
                switch (c)
                {
                    case '"': sb.Append("\\\""); break;
                    case '\\': sb.Append("\\\\"); break;
                    case '\b': sb.Append("\\b"); break;
                    case '\f': sb.Append("\\f"); break;
                    case '\n': sb.Append("\\n"); break;
                    case '\r': sb.Append("\\r"); break;
                    case '\t': sb.Append("\\t"); break;
                    default:
                        if (c < ' ')
                        {
                            sb.Append("\\u").Append(((int)c).ToString("x4",
                                CultureInfo.InvariantCulture));
                        }
                        else
                        {
                            sb.Append(c);
                        }
                        break;
                }
            }
            sb.Append('"');
        }

        private static void CheckRegisterDrift(string repoRoot,
            string mergedText, Report report)
        {
            string p = Path.Combine(repoRoot,
                RegisterRelativePath.Replace('/', Path.DirectorySeparatorChar));
            if (!File.Exists(p))
            {
                Add(report, "register", RegisterRelativePath,
                    "merged register not committed");
                return;
            }
            if (!string.Equals(File.ReadAllText(p), mergedText,
                StringComparison.Ordinal))
            {
                Add(report, "register", RegisterRelativePath,
                    "committed register differs from deterministic fragment"
                    + " merge (regenerate via MergeRegisterText)");
            }
        }

