        /// <summary>Notice text for an already-parsed register.</summary>
        public static string NoticeTextFromRegister(RegisterJson.Node root)
        {
            var sb = new StringBuilder();
            sb.Append("ThinhThan - Third-Party Asset Notices\n\n");
            sb.Append("Generated deterministically by ReleaseAssetAudit"
                + " (IMP-076) from\n");
            sb.Append("client/Assets/Art/Provenance/asset_source_register.json.\n");
            sb.Append("Do not edit by hand.\n\n");
            sb.Append("== Third-Party Credits (CC-BY-4.0) ==\n");
            // Derived blocks carry platform newlines (AppendLine);
            // the packaged notice is canonical LF on every platform.
            string credits = ProvenanceValidator.CreditsText(root);
            sb.Append(credits.Length == 0 ? "(none)\n" : Lf(credits));
            sb.Append("\n== Fonts licensed under the SIL Open Font License 1.1 ==\n");
            string fonts = ProvenanceValidator.FontNotice(root);
            sb.Append(fonts.Length == 0 ? "(none)\n" : Lf(fonts));
            return sb.ToString();
        }

        private static string Lf(string s)
        {
            return s.Replace("\r\n", "\n").Replace("\r", "\n");
        }

        private static void CheckNotice(
            string repoRoot, string mergedText,
            SortedDictionary<string, SortedDictionary<string, string>> groups,
            Dictionary<string, ResolvedEntry> resolved, Report report)
        {
            string p = Path.Combine(repoRoot,
                NoticeRelativePath.Replace('/', Path.DirectorySeparatorChar));
            if (!File.Exists(p))
            {
                Add(report, "notice", NoticeRelativePath,
                    "THIRD_PARTY_ASSETS.txt not committed");
            }
            else
            {
                string expected = NoticeTextFromRegister(
                    RegisterJson.Parse(mergedText));
                if (!string.Equals(File.ReadAllText(p), expected,
                    StringComparison.Ordinal))
                {
                    Add(report, "notice", NoticeRelativePath,
                        "notice differs from deterministic generator output");
                }
            }
            if (!resolved.TryGetValue(CreditsTextKey, out var res))
            {
                Add(report, "notice", CreditsTextKey,
                    "credits key missing or unresolvable in "
                    + AddressableGroups.SharedLocal);
            }
            else
            {
                if (res.Group != AddressableGroups.SharedLocal)
                {
                    Add(report, "notice", CreditsTextKey,
                        "key registered in " + res.Group + " not "
                        + AddressableGroups.SharedLocal);
                }
                if (res.RelPath != NoticeRelativePath)
                {
                    Add(report, "notice", CreditsTextKey,
                        "key resolves to " + res.RelPath);
                }
                if (res.ViaAlias)
                {
                    Add(report, "notice", CreditsTextKey,
                        "notice key must resolve directly, never via alias");
                }
            }
        }

