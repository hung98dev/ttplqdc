        /// <summary>One audit failure, classified for the report.</summary>
        public sealed class Finding
        {
            /// <summary>Check domain: register|provenance|coverage|rights|gate|budget|notice|glyph|placeholder.</summary>
            public string Domain = string.Empty;
            /// <summary>Row file_path, asset key or subject file.</summary>
            public string Subject = string.Empty;
            /// <summary>What failed and why.</summary>
            public string Detail = string.Empty;

            /// <inheritdoc/>
            public override string ToString()
            {
                return Domain + "|" + Subject + "|" + Detail;
            }
        }

        /// <summary>Audit outcome: findings plus coverage counters.</summary>
        public sealed class Report
        {
            /// <summary>All findings, deterministically sorted.</summary>
            public readonly List<Finding> Findings = new List<Finding>();
            /// <summary>Register rows inspected.</summary>
            public int RowsChecked;
            /// <summary>Addressable entries inspected.</summary>
            public int EntriesChecked;
            /// <summary>Expected release keys asserted.</summary>
            public int KeysChecked;
            /// <summary>Media files hash-checked.</summary>
            public int MediaChecked;
            /// <summary>Files run through the ART-* pixel gates.</summary>
            public int GatesRun;

            /// <summary>No findings.</summary>
            public bool Passed
            {
                get
                {
                    return Findings.Count == 0;
                }
            }

            /// <summary>Deterministic one-line-per-finding summary text.</summary>
            public string Summary()
            {
                var sb = new StringBuilder();
                sb.Append("rows=").Append(RowsChecked)
                    .Append(" entries=").Append(EntriesChecked)
                    .Append(" keys=").Append(KeysChecked)
                    .Append(" media=").Append(MediaChecked)
                    .Append(" gated=").Append(GatesRun)
                    .Append(" findings=").Append(Findings.Count)
                    .Append('\n');
                for (int i = 0; i < Findings.Count; i++)
                {
                    sb.Append(Findings[i].ToString()).Append('\n');
                }
                return sb.ToString();
            }

            /// <summary>Findings of one domain.</summary>
            public List<Finding> OfDomain(string domain)
            {
                var list = new List<Finding>();
                for (int i = 0; i < Findings.Count; i++)
                {
                    if (Findings[i].Domain == domain)
                    {
                        list.Add(Findings[i]);
                    }
                }
                return list;
            }
        }

