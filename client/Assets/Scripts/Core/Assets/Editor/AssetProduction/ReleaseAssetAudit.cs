        /// <summary>
        /// Parses every canonical group asset file into
        /// group -> (address -> guid).
        /// </summary>
        public static SortedDictionary<string, SortedDictionary<string, string>>
            LoadGroupEntries(string repoRoot, Report? report = null)
        {
            var map = new SortedDictionary<string, SortedDictionary<string, string>>(
                StringComparer.Ordinal);
            var rx = new Regex(
                @"m_GUID:\s*([0-9a-f]{32})\s*\r?\n\s*m_Address:\s*(\S+)",
                RegexOptions.CultureInvariant);
            var names = AddressableGroups.CanonicalNames();
            for (int i = 0; i < names.Count; i++)
            {
                string name = names[i];
                string p = Path.Combine(repoRoot,
                    (GroupsDir + "/" + name + ".asset").Replace('/',
                        Path.DirectorySeparatorChar));
                if (!File.Exists(p))
                {
                    if (report != null)
                    {
                        Add(report, "coverage", name,
                            "canonical group file missing");
                    }
                    map[name] = new SortedDictionary<string, string>(
                        StringComparer.Ordinal);
                    continue;
                }
                var entries = new SortedDictionary<string, string>(
                    StringComparer.Ordinal);
                foreach (Match m in rx.Matches(File.ReadAllText(p)))
                {
                    entries[m.Groups[2].Value] = m.Groups[1].Value;
                }
                map[name] = entries;
            }
            return map;
        }

        /// <summary>Maps every .meta guid under client/Assets to its asset path.</summary>
        private static Dictionary<string, string> BuildGuidIndex(string repoRoot)
        {
            var index = new Dictionary<string, string>(StringComparer.Ordinal);
            string assetsDir = Path.Combine(repoRoot, "client", "Assets");
            if (!Directory.Exists(assetsDir))
            {
                return index;
            }
            var rx = new Regex(@"^guid:\s*([0-9a-f]{32})\s*$",
                RegexOptions.Multiline | RegexOptions.CultureInvariant);
            foreach (var meta in Directory.GetFiles(assetsDir, "*.meta",
                SearchOption.AllDirectories))
            {
                var m = rx.Match(File.ReadAllText(meta));
                if (!m.Success)
                {
                    continue;
                }
                string rel = meta.Substring(repoRoot.Length + 1)
                    .Replace(Path.DirectorySeparatorChar, '/');
                rel = rel.Substring(0, rel.Length - ".meta".Length);
                index[m.Groups[1].Value] = rel;
            }
            return index;
        }

        private static Dictionary<string, ResolvedEntry> CheckGroupEntries(
            string repoRoot,
            SortedDictionary<string, SortedDictionary<string, string>> groups,
            Dictionary<string, string> guidIndex, List<Row> committedRows,
            Report report)
        {
            var byPath = new Dictionary<string, Row>(StringComparer.Ordinal);
            for (int i = 0; i < committedRows.Count; i++)
            {
                if (committedRows[i].FilePath.Length != 0)
                {
                    byPath[committedRows[i].FilePath] = committedRows[i];
                }
            }
            var resolved = new Dictionary<string, ResolvedEntry>(
                StringComparer.Ordinal);
            foreach (var kv in groups)
            {
                foreach (var e in kv.Value)
                {
                    report.EntriesChecked++;
                    string key = kv.Key + " " + e.Key;
                    if (!AddressableGroups.IsLocalizationGroup(kv.Key))
                    {
                        if (!AssetKey.TryParse(e.Key, out var parsed))
                        {
                            Add(report, "coverage", key,
                                "address is not a valid asset.* key");
                        }
                        else
                        {
                            var want = KeyGroupRule.Assign(parsed);
                            if (want != kv.Key)
                            {
                                Add(report, "coverage", key,
                                    "key routes to " + (want ?? "<none>")
                                    + " not " + kv.Key);
                            }
                            if (e.Key == AssetKey.ObsoleteCreditsKey)
                            {
                                Add(report, "coverage", key,
                                    "obsolete credits key registered");
                            }
                        }
                    }
                    var res = ResolveEntry(repoRoot, e.Value, kv.Key, e.Key,
                        groups, guidIndex, report);
                    if (res == null)
                    {
                        continue;
                    }
                    resolved[e.Key] = res;
                    CheckResolvedType(e.Key, res.RelPath, report);
                    if (ProvenanceValidator.IsMediaFile(res.RelPath))
                    {
                        if (!byPath.TryGetValue(res.RelPath, out var row))
                        {
                            Add(report, "coverage", res.RelPath,
                                "addressable media lacks provenance row");
                        }
                        else if (StrField(row.Node, "review_state")
                            != "APPROVED")
                        {
                            Add(report, "coverage", res.RelPath,
                                "addressable media row not APPROVED");
                        }
                    }
                }
            }
            return resolved;
        }

        private static ResolvedEntry? ResolveEntry(
            string repoRoot, string guid, string group, string addr,
            SortedDictionary<string, SortedDictionary<string, string>> groups,
            Dictionary<string, string> guidIndex, Report report)
        {
            if (!guidIndex.TryGetValue(guid, out var rel))
            {
                Add(report, "coverage", group + " " + addr,
                    "entry guid resolves to no asset");
                return null;
            }
            var res = new ResolvedEntry
            {
                Group = group,
                Address = addr,
                RelPath = rel,
            };
            string abs = Path.Combine(repoRoot,
                rel.Replace('/', Path.DirectorySeparatorChar));
            if (!rel.EndsWith(".asset", StringComparison.Ordinal)
                || !File.Exists(abs))
            {
                return res;
            }
            var text = File.ReadAllText(abs);
            if (text.IndexOf(AliasScriptGuid, StringComparison.Ordinal) < 0)
            {
                return res;
            }
            var tm = Regex.Match(text, @"target_key:\s*(\S+)",
                RegexOptions.CultureInvariant);
            if (!tm.Success)
            {
                Add(report, "coverage", group + " " + addr,
                    "alias asset lacks target_key");
                return null;
            }
            string targetKey = tm.Groups[1].Value;
            string? targetGuid = null;
            foreach (var g in groups.Values)
            {
                if (g.TryGetValue(targetKey, out var tg))
                {
                    targetGuid = tg;
                    break;
                }
            }
            if (targetGuid == null)
            {
                Add(report, "coverage", group + " " + addr,
                    "alias target " + targetKey + " not registered");
                return null;
            }
            if (!guidIndex.TryGetValue(targetGuid, out var trel))
            {
                Add(report, "coverage", group + " " + addr,
                    "alias target guid resolves to no asset");
                return null;
            }
            string tabs = Path.Combine(repoRoot,
                trel.Replace('/', Path.DirectorySeparatorChar));
            if (trel.EndsWith(".asset", StringComparison.Ordinal)
                && File.Exists(tabs)
                && File.ReadAllText(tabs).IndexOf(AliasScriptGuid,
                    StringComparison.Ordinal) >= 0)
            {
                Add(report, "coverage", group + " " + addr,
                    "alias to alias forbidden (" + targetKey + ")");
                return null;
            }
            res.RelPath = trel;
            res.ViaAlias = true;
            return res;
        }

        private static void CheckResolvedType(string key, string relPath,
            Report report)
        {
            if (!AssetKey.TryParse(key, out var parsed))
            {
                return;
            }
            string ext = Path.GetExtension(relPath).ToLowerInvariant();
            bool ok;
            switch (parsed.ExpectedType())
            {
                case AssetKey.ExpectedAssetType.GameObject:
                    ok = ext == ".prefab";
                    break;
                case AssetKey.ExpectedAssetType.SceneAsset:
                    ok = ext == ".unity";
                    break;
                case AssetKey.ExpectedAssetType.Sprite:
                    ok = ext == ".png" || ext == ".psb";
                    break;
                case AssetKey.ExpectedAssetType.AnimationClip:
                    ok = ext == ".anim" || ext == ".controller"
                        || ext == ".png";
                    break;
                case AssetKey.ExpectedAssetType.AudioClip:
                    ok = ext == ".ogg" || ext == ".wav";
                    break;
                case AssetKey.ExpectedAssetType.FontAsset:
                    ok = ext == ".ttf" || ext == ".otf" || ext == ".asset";
                    break;
                case AssetKey.ExpectedAssetType.TextAsset:
                    ok = ext == ".txt";
                    break;
                default:
                    ok = true;
                    break;
            }
            if (!ok)
            {
                Add(report, "coverage", key,
                    "facet " + parsed.Facet + " resolves to " + relPath);
            }
        }

