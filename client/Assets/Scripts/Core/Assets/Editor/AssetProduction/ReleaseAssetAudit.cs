        private static void RunProvenanceValidator(string repoRoot,
            Report report)
        {
            var f = ProvenanceValidator.ValidateFoundation(repoRoot);
            var r = ProvenanceValidator.ValidateRelease(repoRoot);
            for (int i = 0; i < f.Errors.Count; i++)
