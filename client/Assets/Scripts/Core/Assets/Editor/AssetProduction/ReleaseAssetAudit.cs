        /// <summary>
        /// Re-runs the Cutout Quality Gate and Volume &amp; Depth Gate on
        /// every gated release image, plus the style-pack palette gate
        /// (manifest sections 3.1a, 3.2, 3.6; ART-005).
        /// </summary>
        private static void RunArtGates(string repoRoot, List<Row> rows,
            Report report)
        {
            var palettes = new Dictionary<string, List<LabPixels.Lab>>(
                StringComparer.Ordinal);
            var envLayers = new Dictionary<string, List<LabPixels.Lab[]>>(
                StringComparer.Ordinal);
            for (int i = 0; i < rows.Count; i++)
            {
                var row = rows[i];
                string rel = row.FilePath;
                if (!rel.EndsWith(".png", StringComparison.Ordinal)
                    || rel.IndexOf("/StyleRef/", StringComparison.Ordinal) >= 0)
                {
                    continue;
                }
                string abs = Path.Combine(repoRoot,
                    rel.Replace('/', Path.DirectorySeparatorChar));
                if (!File.Exists(abs))
                {
                    continue;
                }
                var cls = GateClassOf(repoRoot, rel, out int cellW,
                    out int cellH, out bool detached, out bool pixelArt,
                    out bool figure, out string? declared);
                if (cls == null)
                {
                    if (declared != null && declared != "FONT_ATLAS"
                        && ClassByName(declared, null) == null)
                    {
                        Add(report, "gate", rel,
                            "unknown declared asset_class " + declared);
                    }
                    continue;
                }
                var img = ArtRuleFixtures.LoadPng(abs);
                var mask = ArtRuleFixtures.LoadTranslucentMask(abs);
                report.GatesRun++;
                if (cellW <= 0 || cellH <= 0)
                {
                    cellW = img.Width;
                    cellH = img.Height;
                }
                int gw = img.Width / cellW;
                int gh = img.Height / cellH;
                if (gw <= 0 || gh <= 0)
                {
                    Add(report, "gate", rel,
                        "image smaller than declared cell");
                    continue;
                }
                for (int cy = 0; cy < gh; cy++)
                {
                    for (int cx = 0; cx < gw; cx++)
                    {
                        var rep = CutoutQualityGate.Measure(abs, img, cx, cy,
                            cellW, cellH, cls.Value, mask, detached, pixelArt);
                        for (int v = 0; v < rep.Violations.Count; v++)
                        {
                            Add(report, "gate", rel + " cell(" + cx + "," + cy
                                + ")", rep.Violations[v]);
                        }
                    }
                }
                RunVolumeGate(repoRoot, rel, abs, img, mask, cls.Value,
                    figure, envLayers, palettes, row, report);
            }
            foreach (var kv in envLayers)
            {
                if (kv.Value.Count < 4)
                {
                    continue;
                }
                var errs = VolumeDepthGate.CheckEnvironmentLayers(kv.Value);
                for (int e = 0; e < errs.Count; e++)
                {
                    Add(report, "gate", "env layers " + kv.Key, errs[e]);
                }
            }
        }

        private static void RunVolumeGate(
            string repoRoot, string rel, string abs, LabPixels.Image img,
            bool[]? mask, CutoutQualityGate.AssetClass cls, bool figure,
            Dictionary<string, List<LabPixels.Lab[]>> envLayers,
            Dictionary<string, List<LabPixels.Lab>> palettes, Row row,
            Report report)
        {
            switch (cls)
            {
                case CutoutQualityGate.AssetClass.Actor:
                case CutoutQualityGate.AssetClass.Prop:
                    var rep = VolumeDepthGate.Measure(abs, img, mask,
                        figure ? 176 : 0, figure ? 192 : 0);
                    for (int v = 0; v < rep.Violations.Count; v++)
                    {
                        Add(report, "gate", rel + " volume", rep.Violations[v]);
                    }
                    break;
                case CutoutQualityGate.AssetClass.Tile:
                    VolumeDepthGate.Silhouette(img, mask, out var inS,
                        out var lab);
                    var sPx = new List<int>();
                    for (int px = 0; px < inS.Length; px++)
                    {
                        if (inS[px])
                        {
                            sPx.Add(px);
                        }
                    }
                    double vr = VolumeDepthGate.ValueRange(sPx, lab);
                    if (double.IsNaN(vr)
                        || vr < VolumeDepthGate.ValueRangeMin)
                    {
                        Add(report, "gate", rel + " volume",
                            "value range L*(p95)-L*(p5) < 40");
                    }
                    var clusters = VolumeDepthGate.HueClusters(sPx, lab,
                        img.Width);
                    int eligible = 0;
                    for (int k = 0; k < clusters.Length; k++)
                    {
                        if (clusters[k].Count != 0
                            && clusters[k].Count * 20 >= sPx.Count)
                        {
                            eligible++;
                        }
                    }
                    double tl = eligible == 0 ? double.NaN
                        : VolumeDepthGate.TopLight(clusters, clusters.Length,
                            sPx.Count, lab, img.Width);
                    if (double.IsNaN(tl) || tl < VolumeDepthGate.TopLightMin)
                    {
                        Add(report, "gate", rel + " volume",
                            "top-light weighted median < 4");
                    }
                    break;
                case CutoutQualityGate.AssetClass.ParallaxNear:
                case CutoutQualityGate.AssetClass.ParallaxFar:
                    // "Môi trường" scope: contributes its opaque Lab layer
                    // to the per-zone ordering check run once per zone set.
                    VolumeDepthGate.Silhouette(img, mask, out var inL,
                        out var labL);
                    var opaque = new List<LabPixels.Lab>();
                    for (int px = 0; px < inL.Length; px++)
                    {
                        if (inL[px])
                        {
                            opaque.Add(labL[px]);
                        }
                    }
                    string zone = ZoneOfParallax(rel);
                    if (!envLayers.TryGetValue(zone, out var set))
                    {
                        set = new List<LabPixels.Lab[]>();
                        envLayers[zone] = set;
                    }
                    set.Add(opaque.ToArray());
                    break;
                default:
                    break;
            }
            // palette gate for image rows carrying a style pack (ART-005)
            var pack = StrField(row.Node, "style_pack_id");
            if (pack == null || pack.Length == 0)
            {
                return;
            }
            if (!palettes.TryGetValue(pack, out var palette))
            {
                palette = LoadPalette(repoRoot, pack);
                palettes[pack] = palette;
            }
            if (palette.Count == 0)
            {
                return;
            }
            VolumeDepthGate.Silhouette(img, mask, out var inP, out var labP);
            var sp = new List<int>();
            for (int px = 0; px < inP.Length; px++)
            {
                if (inP[px])
                {
                    sp.Add(px);
                }
            }
            double cov = VolumeDepthGate.PaletteCoverage(sp, labP, palette);
            if (double.IsNaN(cov) || cov < VolumeDepthGate.PaletteCoverageMin)
            {
                Add(report, "gate", rel + " palette",
                    "coverage below 85% in pack " + pack);
            }
        }

        private static string ZoneOfParallax(string rel)
        {
            // client/Assets/Art/World/<zone>/parallax/* or Instances/<space>/
            var seg = rel.Split('/');
            for (int i = 0; i < seg.Length - 1; i++)
            {
                if (seg[i] == "World" || seg[i] == "Instances")
                {
                    return seg[i] + "/" + seg[i + 1];
                }
            }
            return rel;
        }

        private static List<LabPixels.Lab> LoadPalette(string repoRoot,
            string pack)
        {
            var list = new List<LabPixels.Lab>();
            string p = Path.Combine(repoRoot,
                ("client/Assets/Art/StyleRef/" + pack + "/palette.json")
                .Replace('/', Path.DirectorySeparatorChar));
            if (!File.Exists(p))
            {
                return list;
            }
            var root = RegisterJson.Parse(File.ReadAllText(p));
            var fam = root.Get("families");
            if (fam == null || fam.Type != RegisterJson.Node.Kind.Obj)
            {
                return list;
            }
            foreach (var kv in fam.Obj!)
            {
                var labs = kv.Value.Get("lab");
                if (labs == null || labs.Type != RegisterJson.Node.Kind.Arr)
                {
                    continue;
                }
                for (int i = 0; i < labs.Arr!.Count; i++)
                {
                    var triple = labs.Arr[i];
                    if (triple.Type != RegisterJson.Node.Kind.Arr
                        || triple.Arr!.Count != 3)
                    {
                        continue;
                    }
                    list.Add(new LabPixels.Lab
                    {
                        L = triple.Arr[0].Num,
                        A = triple.Arr[1].Num,
                        B = triple.Arr[2].Num,
                    });
                }
            }
            return list;
        }

        private static Dictionary<string, string>? s_cosmeticClasses;

        /// <summary>
        /// Per-file asset_class lookup built once from
        /// Art/Cosmetics/cosmetic_presentation_map.json: each files[] value
        /// maps to the cosmetic's declared class, except the "icon" slot
        /// which is an ITEM_ICON surface (canonical FileClass rule).
        /// </summary>
        private static Dictionary<string, string> CosmeticClasses(
            string repoRoot)
        {
            if (s_cosmeticClasses != null)
            {
                return s_cosmeticClasses;
            }
            var map = new Dictionary<string, string>(StringComparer.Ordinal);
            string mapPath = Path.Combine(repoRoot,
                ("client/Assets/Art/Cosmetics/cosmetic_presentation_map.json")
                .Replace('/', Path.DirectorySeparatorChar));
            if (File.Exists(mapPath))
            {
                var root = RegisterJson.Parse(File.ReadAllText(mapPath));
                var list = root.Get("cosmetics");
                if (list != null && list.Type == RegisterJson.Node.Kind.Arr)
                {
                    foreach (var c in list.Arr!)
                    {
                        var cls = StrField(c!, "asset_class");
                        var files = c!.Get("files");
                        if (files == null
                            || files.Type != RegisterJson.Node.Kind.Obj)
                        {
                            continue;
                        }
                        foreach (var kv in files.Obj!)
                        {
                            var paths = new List<string>();
                            if (kv.Value.Type == RegisterJson.Node.Kind.Str)
                            {
                                paths.Add(kv.Value.Str);
                            }
                            else if (kv.Value.Type
                                == RegisterJson.Node.Kind.Arr)
                            {
                                foreach (var n in kv.Value.Arr!)
                                {
                                    paths.Add(n.Str);
                                }
                            }
                            foreach (var p in paths)
                            {
                                if (!p.EndsWith(".png",
                                    StringComparison.Ordinal))
                                {
                                    continue;
                                }
                                map[p] = kv.Key == "icon"
                                    ? "ITEM_ICON"
                                    : cls ?? string.Empty;
                            }
                        }
                    }
                }
            }
            s_cosmeticClasses = map;
            return map;
        }

        /// <summary>
        /// Resolves a release image's section 3.1a asset class, authored
        /// cell size (2x texture px), declared flags and whether the file
        /// is a full-figure surface for the 176..192 px body band.
        ///
        /// The declared asset_class in the nearest ancestor import.json /
        /// actor_import.json (or the cosmetic presentation map) is the
        /// dispatch input. The 176..192 band is CHARACTER-scoped: only
        /// player figure surfaces and cosmetic preview/body carry
        /// AssetClass.Actor; creature and NPC cells (declared ACTOR with a
        /// non-CHARACTER profile) run the same full rule set minus the
        /// band, which is exactly AssetClass.Prop's rule set.
        /// Sprite-library slices under /parts/ are sub-sprites, never
        /// standalone presentation, and are not gated.
        /// </summary>
        private static CutoutQualityGate.AssetClass? GateClassOf(
            string repoRoot, string rel, out int cellW, out int cellH,
            out bool detached, out bool pixelArt, out bool figure,
            out string? declared)
        {
            detached = false;
            pixelArt = false;
            figure = false;
            declared = null;
            string name = Path.GetFileName(rel);
            ImportMeta(rel, out cellW, out cellH, out detached, out pixelArt,
                out declared, out string? profile);
            // Cosmetic /parts/ holds sprite-library slices (sub-sprites of a
            // composite appearance), not standalone presentation surfaces —
            // the coverage gate exempts them, so the release audit does too.
            if (rel.IndexOf("/Cosmetics/", StringComparison.Ordinal) >= 0
                && rel.IndexOf("/parts/", StringComparison.Ordinal) >= 0)
            {
                return null;
            }
            if (rel.IndexOf("/Actors/", StringComparison.Ordinal) >= 0)
            {
                figure = FigureSurface(rel, name)
                    && HumanoidProfile(profile);
                return figure
                    ? CutoutQualityGate.AssetClass.Actor
                    : CutoutQualityGate.AssetClass.Prop;
            }
            if (rel.IndexOf("/Cosmetics/", StringComparison.Ordinal) >= 0)
            {
                figure = FigureSurface(rel, name)
                    && HumanoidProfile(profile);
                if (figure)
                {
                    return CutoutQualityGate.AssetClass.Actor;
                }
                string? cosCls = declared;
                if (cosCls == null
                    && CosmeticClasses(repoRoot).TryGetValue(rel, out var cc))
                {
                    cosCls = cc;
                }
                return ClassByName(cosCls,
                    CutoutQualityGate.AssetClass.Prop);
            }
            if (declared != null)
            {
                return ClassByName(declared, null);
            }
            if (rel.IndexOf("/Instances/", StringComparison.Ordinal) >= 0)
            {
                if (name.StartsWith("tile.", StringComparison.Ordinal))
                {
                    return CutoutQualityGate.AssetClass.Tile;
                }
                if (name.StartsWith("bg.far.", StringComparison.Ordinal))
                {
                    return CutoutQualityGate.AssetClass.ParallaxFar;
                }
                if (name.StartsWith("bg.mid.", StringComparison.Ordinal))
                {
                    return CutoutQualityGate.AssetClass.ParallaxNear;
                }
                return CutoutQualityGate.AssetClass.Prop;
            }
            if (rel.IndexOf("/World/", StringComparison.Ordinal) >= 0)
            {
                if (rel.IndexOf("/tiles/", StringComparison.Ordinal) >= 0)
                {
                    return CutoutQualityGate.AssetClass.Tile;
                }
                if (rel.IndexOf("/props/", StringComparison.Ordinal) >= 0
                    || rel.IndexOf("/sig/", StringComparison.Ordinal) >= 0)
                {
                    return CutoutQualityGate.AssetClass.Prop;
                }
                if (rel.IndexOf("/parallax/", StringComparison.Ordinal) >= 0)
                {
                    return name.IndexOf("l2", StringComparison.Ordinal) >= 0
                        || name.StartsWith("fg", StringComparison.Ordinal)
                        ? CutoutQualityGate.AssetClass.ParallaxNear
                        : CutoutQualityGate.AssetClass.ParallaxFar;
                }
                return null;
            }
            if (rel.IndexOf("/Items/", StringComparison.Ordinal) >= 0
                || rel.IndexOf("/UI/Icons/", StringComparison.Ordinal) >= 0)
            {
                return CutoutQualityGate.AssetClass.Prop;
            }
            if (rel.IndexOf("/UI/", StringComparison.Ordinal) >= 0)
            {
                return CutoutQualityGate.AssetClass.UiArt;
            }
            if (rel.IndexOf("/VFX/", StringComparison.Ordinal) >= 0)
            {
                return CutoutQualityGate.AssetClass.VfxSoft;
            }
            return null;
        }

        /// <summary>
        /// True when the file is a full-figure surface (idle sheet,
        /// turnarounds view, assembled preview/body) — the only surfaces the
        /// 176..192 humanoid body band may bind. Composite layer sheets
        /// (*_parts.png) are never figure surfaces.
        /// </summary>
        private static bool FigureSurface(string rel, string name)
        {
            if (name.EndsWith("_parts.png", StringComparison.Ordinal))
            {
                return false;
            }
            if (name.EndsWith("_sheet.png", StringComparison.Ordinal)
                || rel.IndexOf("/turnarounds/", StringComparison.Ordinal) >= 0
                || name == "preview.png" || name == "body.png")
            {
                return true;
            }
            return false;
        }

        /// <summary>
        /// True when the declared size_profile is humanoid (CHARACTER or
        /// NPC_HUMANOID) or undeclared — the only profiles the body band
        /// binds. MONSTER_*/BOSS_*/SPIRIT_BEAST profiles take only their own
        /// bbox limit.
        /// </summary>
        private static bool HumanoidProfile(string? profile)
        {
            return profile == null || profile == "CHARACTER"
                || profile == "NPC_HUMANOID";
        }

        /// <summary>Maps a declared asset_class name to the gate enum.</summary>
        private static CutoutQualityGate.AssetClass? ClassByName(
            string? declared, CutoutQualityGate.AssetClass? fallback)
        {
            switch (declared)
            {
                case "ACTOR":
                case "PROP":
                case "ITEM_ICON":
                case "EQUIPMENT_ICON":
                case "COSMETIC_APPEARANCE":
                    return CutoutQualityGate.AssetClass.Prop;
                case "UI_ART":
                    return CutoutQualityGate.AssetClass.UiArt;
                case "FONT_ATLAS":
                    return null;
                case "TILE":
                    return CutoutQualityGate.AssetClass.Tile;
                case "PARALLAX_NEAR":
                    return CutoutQualityGate.AssetClass.ParallaxNear;
                case "PARALLAX_FAR":
                    return CutoutQualityGate.AssetClass.ParallaxFar;
                case "VFX_SOFT":
                    return CutoutQualityGate.AssetClass.VfxSoft;
                default:
                    return fallback;
            }
        }

        /// <summary>
        /// Reads the file's entry in the nearest ancestor import.json /
        /// actor_import.json: authored cell dims, the detached_parts /
        /// pixel_art flags and the declared asset_class.
        /// </summary>
        private static void ImportMeta(string rel, out int cw, out int ch,
            out bool detached, out bool pixelArt, out string? declared,
            out string? profile)
        {
            cw = 0;
            ch = 0;
            detached = false;
            pixelArt = false;
            declared = null;
            profile = null;
            string dir = Path.GetDirectoryName(rel)!.Replace('\\', '/');
            while (dir.Length > "client/Assets".Length)
            {
                for (int m = 0; m < 2; m++)
                {
                    string man = m == 0 ? "actor_import.json" : "import.json";
                    string p = dir + "/" + man;
                    if (!File.Exists(p))
                    {
                        continue;
                    }
                    var root = RegisterJson.Parse(File.ReadAllText(p));
                    declared = StrField(root, "asset_class");
                    profile = StrField(root, "profile");
                    var tr = root.Get("texture_ref");
                    if (tr != null && tr.Type == RegisterJson.Node.Kind.Arr
                        && tr.Arr!.Count == 2)
                    {
                        cw = (int)tr.Arr[0].Num;
                        ch = (int)tr.Arr[1].Num;
                    }
                    if (cw == 0)
                    {
                        var top = root.Get("cell_ref");
                        CellRef(top, ref cw, ref ch);
                    }
                    var assets = root.Get("assets");
                    string file = Path.GetFileName(rel);
                    if (assets != null
                        && assets.Type == RegisterJson.Node.Kind.Obj
                        && assets.Obj!.TryGetValue(file, out var meta))
                    {
                        profile = StrField(meta, "profile") ?? profile;
                        var d = meta.Get("detached_parts");
                        if (d != null
                            && d.Type == RegisterJson.Node.Kind.Bool
                            && d.Bool)
                        {
                            detached = true;
                        }
                        var px = meta.Get("pixel_art");
                        if (px != null
                            && px.Type == RegisterJson.Node.Kind.Bool
                            && px.Bool)
                        {
                            pixelArt = true;
                        }
                        if (cw == 0)
                        {
                            CellRef(meta.Get("cell_ref"), ref cw, ref ch);
                        }
                    }
                    return;
                }
                int cut = dir.LastIndexOf('/');
                if (cut <= 0)
                {
                    break;
                }
                dir = dir.Substring(0, cut);
            }
        }

        /// <summary>cell_ref is logical px; authored cells are 2x.</summary>
        private static void CellRef(RegisterJson.Node? cr, ref int cw,
            ref int ch)
        {
            if (cr == null)
            {
                return;
            }
            if (cr.Type == RegisterJson.Node.Kind.Num)
            {
                cw = (int)cr.Num * 2;
                ch = cw;
            }
            else if (cr.Type == RegisterJson.Node.Kind.Arr
                && cr.Arr!.Count == 2)
            {
                cw = (int)cr.Arr[0].Num * 2;
                ch = (int)cr.Arr[1].Num * 2;
            }
        }

        // ---------------- helpers ----------------

        private static string? StrField(RegisterJson.Node n, string f)
        {
            var node = n.Get(f);
            return node == null ? null : node.StringOrNull();
        }

        private static bool InSet(string v, string[] set)
        {
            for (int i = 0; i < set.Length; i++)
            {
                if (set[i] == v)
                {
                    return true;
                }
            }
            return false;
        }

        private static void Add(Report report, string domain, string subject,
            string detail)
        {
            report.Findings.Add(new Finding
            {
                Domain = domain,
                Subject = subject,
                Detail = detail,
            });
        }

        private static void SortFindings(Report report)
        {
            report.Findings.Sort((a, b) =>
            {
                int c = string.CompareOrdinal(a.Domain, b.Domain);
                if (c != 0)
                {
                    return c;
                }
                c = string.CompareOrdinal(a.Subject, b.Subject);
                return c != 0 ? c : string.CompareOrdinal(a.Detail, b.Detail);
            });
        }

        private static ushort U16(byte[] b, int o)
        {
            return (ushort)((b[o] << 8) | b[o + 1]);
        }

        private static uint U32(byte[] b, int o)
        {
            return (uint)((b[o] << 24) | (b[o + 1] << 16)
                | (b[o + 2] << 8) | b[o + 3]);
        }
    }
