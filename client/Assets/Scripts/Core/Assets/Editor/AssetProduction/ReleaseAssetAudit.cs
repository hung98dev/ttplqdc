        /// <summary>
        /// Per-row checks against the committed register: required fields,
        /// file presence, final_sha256 vs file bytes, review verdict
        /// consistency with the rights rules.
        /// </summary>
        private static void CheckRowSet(string repoRoot, List<Row> rows,
            HashSet<string> culturalApproved, Report report)
        {
            for (int i = 0; i < rows.Count; i++)
            {
                var row = rows[i];
                var n = row.Node;
                string where = row.FilePath.Length != 0
                    ? row.FilePath
                    : "register[" + i.ToString(CultureInfo.InvariantCulture)
                        + "]";
                foreach (var f in RequiredRowFields)
                {
                    if (n.Get(f) == null)
                    {
                        Add(report, "provenance", where, "missing field " + f);
                    }
                }
                var key = StrField(n, "asset_key");
                if (key != null && !AssetKey.TryParse(key, out _))
                {
                    Add(report, "provenance", where,
                        "asset_key is not a stable asset key");
                }
                string abs = Path.Combine(repoRoot,
                    row.FilePath.Replace('/', Path.DirectorySeparatorChar));
                if (!File.Exists(abs))
                {
                    Add(report, "coverage", where, "file missing on disk");
                }
                else
                {
                    var fin = StrField(n, "final_sha256");
                    if (fin == null || !ProvenanceValidator.IsSha256(fin))
                    {
                        Add(report, "provenance", where,
                            "final_sha256 missing or malformed");
                    }
                    else if (ProvenanceValidator.IsMediaFile(row.FilePath))
                    {
                        report.MediaChecked++;
                        if (!string.Equals(ProvenanceValidator.Sha256File(abs),
                            fin, StringComparison.Ordinal))
                        {
                            Add(report, "provenance", where,
                                "final_sha256 does not match file bytes");
                        }
                        var cid = n.Get("content_id");
                        if (cid != null
                            && cid.Type != RegisterJson.Node.Kind.Str
                            && cid.Type != RegisterJson.Node.Kind.Null)
                        {
                            Add(report, "provenance", where,
                                "content_id must be a catalog id or null");
                        }
                    }
                }
                var verdicts = RowRightsIssues(repoRoot, row,
                    culturalApproved);
                for (int k = 0; k < verdicts.Count; k++)
                {
                    Add(report, "rights", where, verdicts[k]);
                }
                var review = StrField(n, "review_state");
                if (review == "APPROVED" && verdicts.Count != 0)
                {
                    Add(report, "rights", where,
                        "row approved despite rights findings");
                }
                if (review != "APPROVED" && review != "PENDING")
                {
                    Add(report, "rights", where,
                        "unknown review_state " + (review ?? "<null>"));
                }
                if (review == "PENDING" && verdicts.Count == 0)
                {
                    Add(report, "rights", where,
                        "rights-clean row not approved (register stale)");
                }
            }
        }

        /// <summary>
        /// Reverse coverage: every shipped media file under Art/Audio must
        /// carry a register row (manifest section 6 — one record per file).
        /// </summary>
        private static void CheckMediaFiles(string repoRoot,
            List<Row> committedRows, Report report)
        {
            var paths = new HashSet<string>(StringComparer.Ordinal);
            for (int i = 0; i < committedRows.Count; i++)
            {
                paths.Add(committedRows[i].FilePath);
            }
            foreach (var root in MediaRoots)
            {
                string abs = Path.Combine(repoRoot,
                    root.Replace('/', Path.DirectorySeparatorChar));
                if (!Directory.Exists(abs))
                {
                    continue;
                }
                foreach (var f in Directory.GetFiles(abs, "*",
                    SearchOption.AllDirectories))
                {
                    string rel = f.Substring(repoRoot.Length + 1)
                        .Replace(Path.DirectorySeparatorChar, '/');
                    if (!ProvenanceValidator.IsMediaFile(rel))
                    {
                        continue;
                    }
                    if (rel.StartsWith("client/Assets/Art/Provenance/",
                        StringComparison.Ordinal))
                    {
                        continue;
                    }
                    if (!paths.Contains(rel))
                    {
                        Add(report, "coverage", rel,
                            "shipped media file lacks provenance row");
                    }
                }
            }
        }

        /// <summary>
        /// Rights verdict for one row: empty list = APPROVED-eligible.
        /// Commercial modification+distribution requires a launch-allowed
        /// license with resolvable evidence (manifest section 5; ADR-0076).
        /// </summary>
        private static List<string> RowRightsIssues(
            string repoRoot, Row row, HashSet<string> culturalApproved)
        {
            var errs = new List<string>();
            var n = row.Node;
            string kind = StrField(n, "source_kind") ?? string.Empty;
            string lic = StrField(n, "license_id") ?? string.Empty;
            if (!InSet(lic, AllowedLicenses))
            {
                errs.Add("license_id " + (lic.Length == 0 ? "<missing>" : lic)
                    + " not commercially usable for launch");
            }
            if (lic.IndexOf("NC", StringComparison.OrdinalIgnoreCase) >= 0
                || lic.IndexOf("ND", StringComparison.OrdinalIgnoreCase) >= 0
                || lic.IndexOf("SA", StringComparison.OrdinalIgnoreCase) >= 0)
            {
                errs.Add("banned license family (NC/ND/SA)");
            }
            string uri = StrField(n, "source_uri") ?? string.Empty;
            if (kind == "AI_CREATED")
            {
                var gen = n.Get("generation_record");
                if (gen == null || gen.Type != RegisterJson.Node.Kind.Obj)
                {
                    errs.Add("AI_CREATED row lacks generation_record");
                }
                else
                {
                    foreach (var f in RequiredGenFields)
                    {
                        if (gen.Get(f) == null)
                        {
                            errs.Add("generation_record missing " + f);
                        }
                    }
                    var tool = StrField(gen, "tool");
                    if (tool == null || tool.Length == 0)
                    {
                        errs.Add("generation_record.tool empty");
                    }
                    var model = StrField(gen, "model_id");
                    if (model == null || model.Length == 0)
                    {
                        errs.Add("generation_record.model_id empty");
                    }
                    var snap = StrField(gen, "terms_snapshot_sha256");
                    if (snap == null || !ProvenanceValidator.IsSha256(snap))
                    {
                        errs.Add("terms_snapshot_sha256 malformed");
                    }
                    else
                    {
                        // terms/<fragment>/<sha>.txt — the fragment is the
                        // style_pack_id prefix, not the source file name.
                        var pack = StrField(n, "style_pack_id");
                        if (pack == null || !pack.Contains("/"))
                        {
                            errs.Add("cannot resolve terms fragment without"
                                + " a valid style_pack_id");
                        }
                        else
                        {
                            string frag = pack.Substring(0,
                                pack.IndexOf('/'));
                            string tp = Path.Combine(repoRoot,
                                (TermsDir + "/" + frag + "/" + snap
                                + ".txt").Replace('/',
                                    Path.DirectorySeparatorChar));
                            if (!File.Exists(tp))
                            {
                                errs.Add("terms snapshot " + snap
                                    + " not stored under terms/" + frag);
                            }
                            else if (!string.Equals(
                                ProvenanceValidator.Sha256File(tp), snap,
                                StringComparison.Ordinal))
                            {
                                errs.Add("terms snapshot content hash"
                                    + " mismatch");
                            }
                        }
                    }
                }
            }
            else if (kind == "FREE_LICENSED")
            {
                if (lic == "AI_TOOL_TERMS")
                {
                    errs.Add("FREE_LICENSED row uses AI_TOOL_TERMS");
                }
                var attr = StrField(n, "attribution");
                if (attr == null || attr.Length == 0)
                {
                    errs.Add("FREE_LICENSED row lacks attribution");
                }
                if (!uri.StartsWith("http", StringComparison.Ordinal))
                {
                    errs.Add("source_uri not a resolvable page");
                }
                var src = StrField(n, "source_sha256");
                if (src == null || !ProvenanceValidator.IsSha256(src))
                {
                    errs.Add("source_sha256 malformed");
                }
            }
            else
            {
                errs.Add("unknown source_kind " + kind);
            }
            // folklore_card where ART-010 requires it
            if (RequiresFolkloreCard(row))
            {
                var card = n.Get("folklore_card");
                if (card == null || card.Type != RegisterJson.Node.Kind.Obj)
                {
                    errs.Add("folklore_card required (ART-010)");
                }
                else
                {
                    foreach (var f in RequiredCardFields)
                    {
                        var fld = card.Get(f);
                        if (fld == null
                            || fld.Type != RegisterJson.Node.Kind.Arr)
                        {
                            errs.Add("folklore_card." + f + " missing");
                        }
                    }
                }
            }
            // style pack resolvable for image rows
            if (IsImageRow(row))
            {
                var pack = StrField(n, "style_pack_id");
                if (pack == null || pack.Length == 0)
                {
                    errs.Add("image row lacks style_pack_id");
                }
                else
                {
                    string styleMd = Path.Combine(repoRoot,
                        ("client/Assets/Art/StyleRef/" + pack + "/style.md")
                        .Replace('/', Path.DirectorySeparatorChar));
                    string pal = Path.Combine(repoRoot,
                        ("client/Assets/Art/StyleRef/" + pack
                        + "/palette.json")
                        .Replace('/', Path.DirectorySeparatorChar));
                    if (!File.Exists(styleMd) || !File.Exists(pal))
                    {
                        errs.Add("style pack " + pack + " not resolvable");
                    }
                }
            }
            // cultural review cross-check for cosmetics
            if (row.AssetKey.StartsWith("asset.cosmetic.",
                StringComparison.Ordinal)
                && culturalApproved.Count != 0)
            {
                string id = row.AssetKey.Substring("asset.".Length);
                int cut = id.LastIndexOf('.');
                if (cut > 0)
                {
                    id = id.Substring(0, cut);
                }
                if (!culturalApproved.Contains(id))
                {
                    errs.Add("cosmetic " + id
                        + " lacks APPROVED cultural review");
                }
            }
            return errs;
        }

        private static bool RequiresFolkloreCard(Row row)
        {
            string p = row.FilePath;
            if (p.IndexOf("/StyleRef/", StringComparison.Ordinal) >= 0)
            {
                return false;
            }
            if (p.StartsWith("client/Assets/Audio/Bgm/",
                StringComparison.Ordinal))
            {
                // Map/dungeon/instance/zone BGM is a cultural entity;
                // menu and shared utility cues are not (manifest ART-010).
                string k = row.AssetKey;
                if (k.StartsWith("asset.map.", StringComparison.Ordinal)
                    || k.StartsWith("asset.dungeon.", StringComparison.Ordinal)
                    || k.StartsWith("asset.instance.", StringComparison.Ordinal))
                {
                    return true;
                }
                if (k.StartsWith("asset.bgm.", StringComparison.Ordinal)
                    && k.EndsWith(".bgm", StringComparison.Ordinal))
                {
                    var seg = k.Split('.');
                    if (seg.Length == 5
                        && AddressableGroups.IsZoneKey(seg[2]))
                    {
                        return true;
                    }
                }
                return false;
            }
            return p.StartsWith("client/Assets/Art/Actors/",
                    StringComparison.Ordinal)
                || p.StartsWith("client/Assets/Art/Cosmetics/",
                    StringComparison.Ordinal)
                || p.StartsWith("client/Assets/Art/Instances/",
                    StringComparison.Ordinal)
                || p.StartsWith("client/Assets/Art/World/",
                    StringComparison.Ordinal);
        }

        private static bool IsImageRow(Row row)
        {
            string ext = Path.GetExtension(row.FilePath).ToLowerInvariant();
            return ext == ".png" || ext == ".jpg" || ext == ".jpeg"
                || ext == ".tga" || ext == ".psd" || ext == ".psb"
                || ext == ".tif" || ext == ".tiff";
        }

        private static HashSet<string> LoadCulturalApprovals(string repoRoot)
        {
            var set = new HashSet<string>(StringComparer.Ordinal);
            string p = Path.Combine(repoRoot,
                CulturalReviewPath.Replace('/', Path.DirectorySeparatorChar));
            if (!File.Exists(p))
            {
                return set;
            }
            var rx = new Regex(
                @"\|\s*`(cosmetic\.[^`]+)`\s*\|[^|]*\|[^|]*\|\s*APPROVED",
                RegexOptions.CultureInvariant);
            foreach (Match m in rx.Matches(File.ReadAllText(p)))
            {
                set.Add(m.Groups[1].Value);
            }
            return set;
        }

