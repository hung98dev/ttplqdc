        private static void CheckGlyphs(string repoRoot, List<Row> rows,
            Report report)
        {
            for (int i = 0; i < rows.Count; i++)
            {
                string p = rows[i].FilePath;
                if (!p.EndsWith(".ttf", StringComparison.Ordinal)
                    && !p.EndsWith(".otf", StringComparison.Ordinal))
                {
                    continue;
                }
                string abs = Path.Combine(repoRoot,
                    p.Replace('/', Path.DirectorySeparatorChar));
                if (!File.Exists(abs))
                {
                    continue;
                }
                var glyphs = TtfGlyphs(abs);
                if (glyphs == null)
                {
                    Add(report, "glyph", p, "font has no readable cmap");
                    continue;
                }
                foreach (var range in RequiredGlyphRanges)
                {
                    for (int cp = range.lo; cp <= range.hi; cp++)
                    {
                        if (!glyphs.Contains(cp))
                        {
                            Add(report, "glyph", p,
                                "missing glyph U+" + cp.ToString("X4",
                                    CultureInfo.InvariantCulture));
                        }
                    }
                }
            }
        }

        private static HashSet<int>? TtfGlyphs(string path)
        {
            byte[] b;
            try
            {
                b = File.ReadAllBytes(path);
            }
            catch (IOException)
            {
                return null;
            }
            if (b.Length < 12)
            {
                return null;
            }
            int numTables = (b[4] << 8) | b[5];
            int cmap = 0;
            for (int i = 0; i < numTables; i++)
            {
                int rec = 12 + i * 16;
                if (rec + 16 > b.Length)
                {
                    break;
                }
                if (b[rec] == 'c' && b[rec + 1] == 'm' && b[rec + 2] == 'a'
                    && b[rec + 3] == 'p')
                {
                    cmap = (int)U32(b, rec + 8);
                    break;
                }
            }
            if (cmap == 0 || cmap + 4 > b.Length)
            {
                return null;
            }
            int subs = U16(b, cmap + 2);
            int chosen = 0;
            int fmt = 0;
            for (int i = 0; i < subs; i++)
            {
                int er = cmap + 4 + i * 8;
                if (er + 8 > b.Length)
                {
                    break;
                }
                int sub = cmap + (int)U32(b, er + 4);
                if (sub + 2 > b.Length || sub < 0)
                {
                    continue;
                }
                int f = U16(b, sub);
                if (f == 12 || (fmt == 0 && f == 4))
                {
                    chosen = sub;
                    fmt = f;
                    if (f == 12)
                    {
                        break;
                    }
                }
            }
            if (chosen == 0)
            {
                return null;
            }
            var set = new HashSet<int>();
            if (fmt == 12)
            {
                long nGroups = U32(b, chosen + 12);
                int g = chosen + 16;
                for (long i = 0; i < nGroups; i++)
                {
                    if (g + 12 > b.Length)
                    {
                        break;
                    }
                    int start = (int)U32(b, g);
                    int end = (int)U32(b, g + 4);
                    for (int cp = start; cp <= end && cp <= 0x10FFFF; cp++)
                    {
                        set.Add(cp);
                    }
                    g += 12;
                }
            }
            else
            {
                int segCount = U16(b, chosen + 6) / 2;
                int endBase = chosen + 14;
                int startBase = endBase + segCount * 2 + 2;
                for (int i = 0; i < segCount; i++)
                {
                    if (startBase + i * 2 + 2 > b.Length)
                    {
                        break;
                    }
                    int end = U16(b, endBase + i * 2);
                    int start = U16(b, startBase + i * 2);
                    for (int cp = start; cp <= end && cp != 0xFFFF; cp++)
                    {
                        set.Add(cp);
                    }
                }
            }
            return set;
        }

