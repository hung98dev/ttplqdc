        /// <summary>
        /// Runs the full audit and returns the report; the audit itself
        /// never writes files — artifacts are regenerated via
        /// <see cref="MergeRegisterText"/>, <see cref="RightsReviewText"/>
        /// and <see cref="NoticeText"/> and compared byte-for-byte.
        /// </summary>
        public static Report Run(string repoRoot, bool runArtGates = true)
        {
            var report = new Report();
            var rows = LoadRows(repoRoot, report);
            var culturalApproved = LoadCulturalApprovals(repoRoot);
            var committedRows = LoadCommittedRegister(repoRoot, report);
            CheckRowSet(repoRoot, committedRows, culturalApproved, report);
            CheckMediaFiles(repoRoot, committedRows, report);
            string mergedText = MergeRegisterTextFromRows(repoRoot, rows,
                culturalApproved);
            CheckRegisterDrift(repoRoot, mergedText, report);
            RunProvenanceValidator(repoRoot, report);
            var groups = LoadGroupEntries(repoRoot, report);
            var guidIndex = BuildGuidIndex(repoRoot);
            var resolved = CheckGroupEntries(repoRoot, groups, guidIndex,
                committedRows, report);
            CheckRosterKeys(repoRoot, rows, groups, report);
            CheckBudgets(repoRoot, resolved, report);
            CheckNotice(repoRoot, mergedText, groups, resolved, report);
            CheckRightsDoc(repoRoot, report);
            CheckGlyphs(repoRoot, committedRows, report);
            CheckPlaceholders(repoRoot, committedRows, report);
            if (runArtGates)
            {
                RunArtGates(repoRoot, committedRows, report);
            }
            SortFindings(report);
            return report;
        }

