        private static void CheckRosterKeys(
            string repoRoot, List<Row> rows,
            SortedDictionary<string, SortedDictionary<string, string>> groups,
            Report report)
        {
            // 33 playable spaces: scene + bgm keys in canonical groups
            string mapsDir = Path.Combine(repoRoot,
                SpaceGeometryDir.Replace('/', Path.DirectorySeparatorChar));
            if (Directory.Exists(mapsDir))
            {
                var spaces = new List<string>();
                foreach (var f in Directory.GetFiles(mapsDir, "*.geom.json"))
                {
                    string stem = Path.GetFileName(f);
                    stem = stem.Substring(0, stem.Length - ".geom.json".Length);
                    spaces.Add(stem);
                }
                spaces.Sort(StringComparer.Ordinal);
                for (int i = 0; i < spaces.Count; i++)
                {
                    string space = spaces[i];
                    ExpectKeyInGroup(report, groups,
                        "asset." + space + ".scene",
                        AddressableGroups.SpaceGroup(space));
                    ExpectKeyInGroup(report, groups,
                        "asset." + space + ".bgm",
                        AddressableGroups.SpaceBgmGroup(space));
                }
            }
            // SFX cues: every clip file maps to a shared.local key
            string sfxDir = Path.Combine(repoRoot,
                "client/Assets/Audio/Sfx".Replace('/',
                    Path.DirectorySeparatorChar));
            if (Directory.Exists(sfxDir))
            {
                var oggs = Directory.GetFiles(sfxDir, "*.ogg");
                Array.Sort(oggs, StringComparer.Ordinal);
                foreach (var f in oggs)
                {
                    ExpectKeyInGroup(report, groups,
                        "asset.sfx." + Path.GetFileNameWithoutExtension(f)
                        + ".clip", AddressableGroups.SharedLocal);
                }
            }
            ExpectActorKeys(repoRoot, groups, report);
            ExpectCosmeticKeys(repoRoot, groups, report);
            ExpectSkillVfxTwins(rows, groups, report);
            // Every non-styleref fragment asset_key that parses must be a
            // registered group address.
            var seen = new HashSet<string>(StringComparer.Ordinal);
            for (int i = 0; i < rows.Count; i++)
            {
                string key = rows[i].AssetKey;
                if (key.Length == 0 || !seen.Add(key)
                    || key.IndexOf(".styleref.", StringComparison.Ordinal) >= 0)
                {
                    continue;
                }
                if (!AssetKey.TryParse(key, out var parsed))
                {
                    continue;
                }
                report.KeysChecked++;
                var want = KeyGroupRule.Assign(parsed);
                if (want == null)
                {
                    Add(report, "coverage", key,
                        "fragment-declared key has no canonical group");
                    continue;
                }
                if (!groups.TryGetValue(want, out var entries)
                    || !entries.ContainsKey(key))
                {
                    Add(report, "coverage", key,
                        "fragment-declared key missing from group " + want);
                }
            }
        }

        private static void ExpectKeyInGroup(
            Report report,
            SortedDictionary<string, SortedDictionary<string, string>> groups,
            string key, string? group)
        {
            report.KeysChecked++;
            if (group == null)
            {
                Add(report, "coverage", key, "key has no canonical group");
                return;
            }
            if (!groups.TryGetValue(group, out var entries)
                || !entries.ContainsKey(key))
            {
                Add(report, "coverage", key, "missing entry in group " + group);
            }
        }

        /// <summary>Key must be registered somewhere and routed canonically.</summary>
        private static void ExpectKeyAnywhere(
            Report report,
            SortedDictionary<string, SortedDictionary<string, string>> groups,
            string key)
        {
            report.KeysChecked++;
            if (!AssetKey.TryParse(key, out var parsed))
            {
                Add(report, "coverage", key, "expected key fails to parse");
                return;
            }
            var want = KeyGroupRule.Assign(parsed);
            foreach (var kv in groups)
            {
                if (!kv.Value.ContainsKey(key))
                {
                    continue;
                }
                if (want != kv.Key)
                {
                    Add(report, "coverage", key,
                        "registered in " + kv.Key + " not "
                        + (want ?? "<none>"));
                }
                return;
            }
            Add(report, "coverage", key, "expected key has no group entry");
        }

        private static void ExpectActorKeys(
            string repoRoot,
            SortedDictionary<string, SortedDictionary<string, string>> groups,
            Report report)
        {
            string actorsDir = Path.Combine(repoRoot,
                "client/Assets/Art/Actors".Replace('/',
                    Path.DirectorySeparatorChar));
            if (!Directory.Exists(actorsDir))
            {
                return;
            }
            // beast element comes from the fragment-declared anim keys
            var beastElem = new Dictionary<string, string>(StringComparer.Ordinal);
            string actorsFrag = Path.Combine(repoRoot,
                (FragmentsDir + "/actors_creatures.json").Replace('/',
                    Path.DirectorySeparatorChar));
            if (File.Exists(actorsFrag))
            {
                var root = RegisterJson.Parse(File.ReadAllText(actorsFrag));
                var arr = root.Get("assets");
                if (arr != null && arr.Type == RegisterJson.Node.Kind.Arr)
                {
                    var rx = new Regex(@"^asset\.beast\.([^.]+)\.([^.]+)\.",
                        RegexOptions.CultureInvariant);
                    for (int i = 0; i < arr.Arr!.Count; i++)
                    {
                        var k = StrField(arr.Arr[i], "asset_key");
                        if (k == null)
                        {
                            continue;
                        }
                        var m = rx.Match(k);
                        if (m.Success)
                        {
                            beastElem[m.Groups[2].Value] = m.Groups[1].Value;
                        }
                    }
                }
            }
            foreach (var dir in Directory.GetDirectories(actorsDir, "*",
                SearchOption.TopDirectoryOnly))
            {
                string top = Path.GetFileName(dir);
                if (top == "Players")
                {
                    foreach (var c in Directory.GetDirectories(dir))
                    {
                        ExpectKeyAnywhere(report, groups,
                            "asset.class." + Path.GetFileName(c) + ".prefab");
                    }
                    continue;
                }
                foreach (var zone in Directory.GetDirectories(dir))
                {
                    string z = Path.GetFileName(zone);
                    if (top == "Npcs")
                    {
                        foreach (var npc in Directory.GetDirectories(zone))
                        {
                            ExpectKeyAnywhere(report, groups,
                                "asset.npc." + z + "." + Path.GetFileName(npc)
                                + ".prefab");
                        }
                    }
                    else if (top == "Creatures")
                    {
                        if (z == "spirit_beasts")
                        {
                            foreach (var b in Directory.GetDirectories(zone))
                            {
                                string name = Path.GetFileName(b);
                                if (!beastElem.TryGetValue(name, out var elem))
                                {
                                    Add(report, "coverage",
                                        "spirit_beasts/" + name,
                                        "beast element not derivable from"
                                        + " fragment keys");
                                    continue;
                                }
                                ExpectKeyAnywhere(report, groups,
                                    "asset.beast." + elem + "." + name
                                    + ".prefab");
                            }
                        }
                        else if (z == "bosses")
                        {
                            foreach (var b in Directory.GetDirectories(zone))
                            {
                                ExpectKeyAnywhere(report, groups,
                                    "asset.boss." + Path.GetFileName(b)
                                    + ".prefab");
                            }
                        }
                        else
                        {
                            foreach (var mn in Directory.GetDirectories(zone))
                            {
                                ExpectKeyAnywhere(report, groups,
                                    "asset.monster." + z + "."
                                    + Path.GetFileName(mn) + ".prefab");
                            }
                        }
                    }
                }
            }
        }

        private static void ExpectCosmeticKeys(
            string repoRoot,
            SortedDictionary<string, SortedDictionary<string, string>> groups,
            Report report)
        {
            string p = Path.Combine(repoRoot,
                CosmeticMapPath.Replace('/', Path.DirectorySeparatorChar));
            if (!File.Exists(p))
            {
                Add(report, "coverage", CosmeticMapPath,
                    "cosmetic presentation map missing");
                return;
            }
            var root = RegisterJson.Parse(File.ReadAllText(p));
            var cs = root.Get("cosmetics");
            if (cs == null || cs.Type != RegisterJson.Node.Kind.Arr)
            {
                Add(report, "coverage", CosmeticMapPath,
                    "cosmetics array missing");
                return;
            }
            for (int i = 0; i < cs.Arr!.Count; i++)
            {
                var keys = cs.Arr[i].Get("keys");
                if (keys == null || keys.Type != RegisterJson.Node.Kind.Obj)
                {
                    continue;
                }
                foreach (var kv in keys.Obj!)
                {
                    var key = kv.Value.StringOrNull();
                    if (key == null)
                    {
                        continue;
                    }
                    ExpectKeyAnywhere(report, groups, key);
                }
            }
        }

        private static void ExpectSkillVfxTwins(
            List<Row> rows,
            SortedDictionary<string, SortedDictionary<string, string>> groups,
            Report report)
        {
            var seen = new HashSet<string>(StringComparer.Ordinal);
            for (int i = 0; i < rows.Count; i++)
            {
                string key = rows[i].AssetKey;
                if (!key.StartsWith("asset.skill.", StringComparison.Ordinal)
                    || !key.EndsWith(".icon", StringComparison.Ordinal))
                {
                    continue;
                }
                string twin = key.Substring(0, key.Length - ".icon".Length)
                    + ".vfx";
                if (!seen.Add(twin))
                {
                    continue;
                }
                ExpectKeyInGroup(report, groups, twin,
                    AddressableGroups.SharedLocal);
            }
        }

